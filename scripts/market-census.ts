/**
 * Which markets SportyBet lists on its football games today, and how the
 * code reader reads each: our model, our goal-timing estimate, or SportyBet's
 * own chance. Writes docs/sportybet-markets.md.
 *
 * Read-only: one board page and one event read per game, a second apart, on
 * the same public JSON the mobile site uses (src/lib/odds/sportybet-direct.ts).
 *
 *   npx tsx scripts/market-census.ts [games]      (default 40)
 */
import { writeFileSync } from "node:fs";
import { leadChance } from "../src/lib/model/lead-process";
import { fromSportyBet, type SportyBetSelection } from "../src/lib/odds/markets";
import { rawGrader } from "../src/lib/odds/raw-grades";

const BASE = "https://www.sportybet.com/api/ng";
const HEADERS = {
  "User-Agent": "Mozilla/5.0 (Linux; Android 13; Pixel 7) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Mobile Safari/537.36",
  Accept: "application/json",
  Referer: "https://www.sportybet.com/ng/m/",
  Origin: "https://www.sportybet.com",
};
const RATES = { first: { home: 0.6, away: 0.5 }, second: { home: 0.75, away: 0.6 } };

interface ApiMarket {
  id: string | number;
  desc?: string;
  specifier?: string;
  outcomes?: { id: string; desc?: string }[];
}

const get = async (path: string) => {
  const r = await fetch(`${BASE}${path}`, { headers: HEADERS, signal: AbortSignal.timeout(15_000) });
  return r.ok ? ((await r.json()) as { data?: unknown }) : null;
};
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** How the reader reads an outcome now. */
function readBy(sel: SportyBetSelection): "model" | "estimate" | "market" {
  if (fromSportyBet(sel)) return "model";
  const g = rawGrader(sel);
  if (g) return "model";
  return leadChance(sel, RATES) !== null ? "estimate" : "market";
}

async function main() {
  const want = Number(process.argv[2] ?? 40);
  // Spread across competitions: the first event of each tournament on the board, then more.
  const board = (await get(`/factsCenter/pcUpcomingEvents?sportId=sr%3Asport%3A1&marketId=1&pageSize=99&pageNum=1&option=1`)) as {
    data?: { tournaments?: { name: string; events: { eventId: string }[] }[] };
  } | null;
  const tournaments = board?.data?.tournaments ?? [];
  const picks: { eventId: string; league: string }[] = [];
  for (let round = 0; picks.length < want && round < 5; round++) {
    for (const t of tournaments) {
      const e = t.events[round];
      if (e && picks.length < want) picks.push({ eventId: e.eventId, league: t.name });
    }
  }

  const seen = new Map<string, { desc: string; games: number; outcomes: number; by: Map<string, number>; specs: Set<string> }>();
  let games = 0;
  for (const p of picks) {
    const body = (await get(`/factsCenter/event?eventId=${p.eventId}&productId=3`)) as { data?: { markets?: ApiMarket[] } } | null;
    await sleep(1000);
    const markets = body?.data?.markets;
    if (!markets?.length) continue;
    games++;
    const here = new Set<string>();
    for (const m of markets) {
      const id = String(m.id);
      const row = seen.get(id) ?? { desc: m.desc ?? "", games: 0, outcomes: 0, by: new Map(), specs: new Set() };
      if (!here.has(id)) row.games++;
      here.add(id);
      if (m.specifier) row.specs.add(m.specifier.replace(/\d+(\.\d+)?/g, "N"));
      for (const o of m.outcomes ?? []) {
        const by = readBy({ marketId: id, outcomeId: String(o.id), ...(m.specifier ? { specifier: m.specifier } : {}) });
        row.outcomes++;
        row.by.set(by, (row.by.get(by) ?? 0) + 1);
      }
      seen.set(id, row);
    }
  }

  const rows = [...seen.entries()].sort((a, b) => b[1].games - a[1].games || Number(a[0]) - Number(b[0]));
  const share = (x: { by: Map<string, number>; outcomes: number }, k: string) => (x.by.get(k) ?? 0) / x.outcomes;
  const label = (x: { by: Map<string, number>; outcomes: number }) =>
    share(x, "model") === 1 ? "model" : share(x, "estimate") === 1 ? "estimate" : share(x, "market") === 1 ? "SportyBet's chance" :
    ["model", "estimate", "market"].filter((k) => share(x, k) > 0).map((k) => `${k === "market" ? "SportyBet" : k} ${Math.round(share(x, k) * 100)}%`).join(", ");
  const total = { model: 0, estimate: 0, market: 0 };
  for (const [, x] of rows) for (const k of ["model", "estimate", "market"] as const) total[k] += x.by.get(k) ?? 0;
  const all = total.model + total.estimate + total.market;

  const md = [
    "# SportyBet's football markets, and how the code reader reads them",
    "",
    `Generated by \`scripts/market-census.ts\` on ${new Date().toISOString().slice(0, 10)} from ${games} upcoming games across ${new Set(picks.map((p) => p.league)).size} competitions. Re-run it to refresh.`,
    "",
    "Every pick on a pasted code is read; nothing is refused for its market. Each outcome is read, in order of preference, by:",
    "",
    "- **model**: our own chance from the match's score grids (full-match, both halves, or the corners count model): `src/lib/odds/markets.ts`, `src/lib/odds/raw-grades.ts`, `src/lib/leg-pricing.ts`.",
    "- **estimate**: our goal-timing estimate for markets settled on when goals come (1UP, 2UP, lead by N, first goal, minute markets): `src/lib/model/lead-process.ts`. Labelled as an estimate and never called strong.",
    "- **SportyBet's chance**: the probability SportyBet quotes beside the outcome (margin out), for player markets, bookings and anything else: `src/lib/odds/market-read.ts`.",
    "",
    `Across every outcome listed: model ${Math.round((total.model / all) * 100)}%, estimate ${Math.round((total.estimate / all) * 100)}%, SportyBet's chance ${Math.round((total.market / all) * 100)}%.`,
    "",
    "| id | market | on games | specifier shapes | read by |",
    "| ---: | --- | ---: | --- | --- |",
    ...rows.map(([id, x]) => `| ${id} | ${x.desc.replace(/\|/g, "/")} | ${Math.round((x.games / games) * 100)}% | ${[...x.specs].slice(0, 3).join(", ").replace(/\|/g, "&#124;") || "–"} | ${label(x)} |`),
    "",
  ].join("\n");
  writeFileSync("docs/sportybet-markets.md", md);
  console.log(`${games} games, ${rows.length} markets; model ${total.model}, estimate ${total.estimate}, market ${total.market}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
